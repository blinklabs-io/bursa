// Reference certificates generated by cardano-cli 11.0.0.0
// `conway stake-pool registration-certificate --mainnet` with
// pledge 1000000000, cost 340000000, margin 0.03, the cold, VRF and stake
// verification keys written by runPoolRegistration, and the reward account
// and owner given as the stake key file. The second owner is
// testStakeVKeyCborHex.
const (
	poolRegPrefix = "8a03581c3984ee65457a47e2c847c9a9a3870d466e06a13d3fb08b5b29dfeb22" +
		"5820503336f71cf9f2579b56a9c9be1471fe5631a5555e187b6b677f984fa89e7f07" +
		"1a3b9aca001a1443fd00d81e82031864" +
		"581de1e557890352095f1cf6fd2b7d1a28e3c3cb029f48cf34ff890a28d176"
	ownerSelf    = "581ce557890352095f1cf6fd2b7d1a28e3c3cb029f48cf34ff890a28d176"
	ownerOther   = "581cd88b9f136cc94612ed33dd8774c6f43db347ae5814d8efd725d39313"
	ownerSetOne  = "d9010281" + ownerSelf
	ownerSetTwo  = "d9010282" + ownerOther + ownerSelf
	relayIPv4    = "8400190bb94401020304f6"
	relayIPv6    = "8400190bbaf650b80d0120000000000000000001000000"
	relayHostP   = "8301190bb96d722e6578616d706c652e636f6d"
	relayHostNoP = "8301f66d732e6578616d706c652e636f6d"
	relayMulti   = "82026d6d2e6578616d706c652e636f6d"
	noMetadata   = "f6"
)

func runPoolRegistration(
	t *testing.T,
	ownerVkeys []string,
	relays PoolRelayFlags,
) (string, error) {
	t.Helper()
	tmpDir := t.TempDir()
	coldVkey := createTestVkeyFile(
		t, tmpDir, "cold.vkey",
		"StakePoolVerificationKey_ed25519",
		"Stake Pool Operator Verification Key",
		testColdVKeyCborHex,
	)
	vrfVkey := createTestVkeyFile(
		t, tmpDir, "vrf.vkey",
		"VrfVerificationKey_PraosVRF",
		"VRF Verification Key",
		testVRFVKeyCborHex,
	)
	var ownerFiles []string
	for i, owner := range ownerVkeys {
		ownerFiles = append(ownerFiles, createTestVkeyFile(
			t, tmpDir, "owner"+string(rune('0'+i))+".vkey",
			"StakeVerificationKeyShelley_ed25519",
			"Stake Verification Key",
			owner,
		))
	}
	outFile := filepath.Join(tmpDir, "pool-reg.cert")
	err := RunCertPoolRegistration(
		coldVkey, vrfVkey, goldenStakeAddr, outFile,
		1_000_000_000, 340_000_000, 0.03, "", "",
		ownerFiles, relays,
	)
	if err != nil {
		return "", err
	}
	data, err := os.ReadFile(outFile)
	require.NoError(t, err)
	var env map[string]string
	require.NoError(t, json.Unmarshal(data, &env))
	return env["cborHex"], nil
}

func TestRunCertPoolRegistration_MatchesCardanoCLI(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		owners []string
		relays PoolRelayFlags
		want   string
	}{
		{
			name: "default owner is reward account stake key",
			want: poolRegPrefix + ownerSetOne + "80" + noMetadata,
		},
		{
			name:   "explicit owner stake vkey",
			owners: []string{goldenStakeVKeyCborHex},
			want:   poolRegPrefix + ownerSetOne + "80" + noMetadata,
		},
		{
			name: "multiple owners are a sorted set",
			owners: []string{
				goldenStakeVKeyCborHex, testStakeVKeyCborHex,
			},
			want: poolRegPrefix + ownerSetTwo + "80" + noMetadata,
		},
		{
			name: "address, host and multi host relays",
			relays: PoolRelayFlags{
				Addresses:  []string{"1.2.3.4:3001"},
				Hosts:      []string{"r.example.com:3001", "s.example.com"},
				MultiHosts: []string{"m.example.com"},
			},
			want: poolRegPrefix + ownerSetOne + "84" + relayIPv4 +
				relayHostP + relayHostNoP + relayMulti + noMetadata,
		},
		{
			name: "ipv6 relay",
			relays: PoolRelayFlags{
				Addresses: []string{"[2001:db8::1]:3002"},
			},
			want: poolRegPrefix + ownerSetOne + "81" + relayIPv6 +
				noMetadata,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := runPoolRegistration(t, tc.owners, tc.relays)
			require.NoError(t, err)
			assert.Equal(t, tc.want, got)
		})
	}
}

func TestRunCertPoolRegistration_RejectsInvalidRelays(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		relays PoolRelayFlags
	}{
		{"address without port", PoolRelayFlags{Addresses: []string{"1.2.3.4"}}},
		{"address not an ip", PoolRelayFlags{Addresses: []string{"example.com:3001"}}},
		{"address port out of range", PoolRelayFlags{Addresses: []string{"1.2.3.4:70000"}}},
		{"host bad port", PoolRelayFlags{Hosts: []string{"r.example.com:abc"}}},
		{"empty host", PoolRelayFlags{Hosts: []string{":3001"}}},
		{"empty multi host", PoolRelayFlags{MultiHosts: []string{""}}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			_, err := runPoolRegistration(t, nil, tc.relays)
			require.Error(t, err)
			assert.Contains(t, err.Error(), "relay")
		})
	}
}

func TestRunCertPoolRegistration_RejectsBadOwnerVkey(t *testing.T) {
	t.Parallel()
	_, err := runPoolRegistration(t, []string{"5820abcd"}, PoolRelayFlags{})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "owner")
}
